#!/usr/bin/env node
// dev/make-spacestation-wordmark.mjs — generate frontend/assets/brand/spacestation-wordmark.svg.
//
// WHY A PIXEL MATRIX, AND WHY A SCRIPT
//   The masthead mark is a CSS MASK over this SVG (style.css .logo-img). A mask loader parses the
//   file as strict XML and reads only its ALPHA, so the asset must be:
//     - a single well-formed <svg> root (no doctype / stylesheet PI),
//     - built from real <path> geometry (a <text> element would render in whatever font the loader
//       happens to have, which is exactly the silent failure the mask test exists to catch),
//     - a viewBox whose aspect-ratio style.css copies EXACTLY (a masked <span> has no intrinsic
//       size, so the CSS aspect-ratio is the only thing giving it a width).
//   A 5x7 terminal matrix satisfies all three and matches the station's pixel-art identity. The
//   matrix is drawn here rather than traced because SpaceStation has no legacy master art to trace
//   (the StarNet wordmark was traced from its own PNG by dev/trace-logo.mjs; that asset is left
//   untouched). Regenerate with:  node dev/make-spacestation-wordmark.mjs
//
//   THE FILL IS EXPLICIT, NOT currentColor. This one asset is used two ways: as the masthead MASK
//   (alpha only — the element paints var(--ph) itself, so the fill colour is irrelevant there) and
//   as an <img> on the splash and in README.md. An SVG loaded via <img> has no page to inherit from,
//   so `fill="currentColor"` resolves to the initial colour — near-black — and the mark vanishes on
//   the dark title screen and on GitHub dark mode. The project's other standalone SVG (the favicon)
//   hardcodes its colours for the same reason. DEFAULT_PHOSPHOR matches --ph in the default theme.
//
//   Every pixel is emitted as its own closed subpath of ONE <path>, so the whole wordmark is a
//   single fill — no per-glyph groups, no transforms, nothing a mask loader has to resolve.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'frontend', 'assets', 'brand', 'spacestation-wordmark.svg');

// --ph in style.css's default (amber) theme — the same gold the legacy PNG logo used.
const DEFAULT_PHOSPHOR = '#ffaa33';

// ---- the 5x7 glyphs (1 = lit). Only the letters in SPACESTATION are defined. ----
const GLYPHS = {
  S: ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
  P: ['11110', '10001', '10001', '11110', '10000', '10000', '10000'],
  A: ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
  C: ['01110', '10001', '10000', '10000', '10000', '10001', '01110'],
  E: ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
  T: ['11111', '00100', '00100', '00100', '00100', '00100', '00100'],
  I: ['11111', '00100', '00100', '00100', '00100', '00100', '11111'],
  O: ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
  N: ['10001', '11001', '10101', '10011', '10001', '10001', '10001'],
};

const WORD = 'SPACESTATION';
const GW = 5, GH = 7;        // glyph cell grid
const CELL = 20;             // px per cell
const GAP = 20;              // px between glyphs (one cell)
const INSET = 1;             // px inset per pixel — a hairline matrix seam, echoes the mosaic texture
const PAD = 20;              // px padding around the whole word

const PX = CELL - 2 * INSET;

const d = [];
WORD.split('').forEach((ch, g) => {
  const rows = GLYPHS[ch];
  if (!rows) throw new Error(`no glyph for "${ch}"`);
  if (rows.length !== GH || rows.some(r => r.length !== GW)) throw new Error(`glyph "${ch}" is not ${GW}x${GH}`);
  const gx = PAD + g * (GW * CELL + GAP);
  rows.forEach((row, r) => {
    for (let c = 0; c < GW; c++) {
      if (row[c] !== '1') continue;
      const x = gx + c * CELL + INSET;
      const y = PAD + r * CELL + INSET;
      d.push(`M${x} ${y}h${PX}v${PX}h-${PX}z`);
    }
  });
});

const width = PAD * 2 + WORD.length * GW * CELL + (WORD.length - 1) * GAP;
const height = PAD * 2 + GH * CELL;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-label="SPACESTATION">
<title>SPACESTATION</title>
<!-- Generated by dev/make-spacestation-wordmark.mjs — do not hand-edit.
     A 5x7 terminal matrix drawn as one <path>. The fill is an explicit phosphor, not currentColor,
     because this asset is also loaded via <img> (splash, README) where currentColor would resolve
     to near-black. The viewBox aspect-ratio (${width}/${height}) is copied verbatim into
     style.css .logo-img; change one, change the other. -->
<path fill="${DEFAULT_PHOSPHOR}" d="${d.join('')}"/>
</svg>
`;

writeFileSync(OUT, svg);
console.log(`wrote ${path.relative(REPO, OUT)}  (${WORD.length} glyphs, ${d.length} pixels, viewBox 0 0 ${width} ${height})`);
